fn expansion() {
    {
        let mut builder = ::typespace::TypespaceBuilder::<
            String,
        >::new(Settings::typical());
        builder
            .insert(
                "u32".to_string(),
                ::typespace::build::Type::Integer("u32".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "Item".to_string(),
                ::typespace::build::Struct::<String>::new()
                    .name("Item")
                    .properties([
                        ::typespace::build::StructProperty::new(
                                "value",
                                "u32".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                    ])
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
            .insert(
                "Nullable<Item>".to_string(),
                ::typespace::build::Type::Option("Item".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "Vec<Nullable<Item>>".to_string(),
                ::typespace::build::Type::Vec("Nullable<Item>".to_string()),
            )
            .unwrap();
        builder.insert("String".to_string(), ::typespace::build::Type::String).unwrap();
        builder
            .insert(
                "Map<String, Item>".to_string(),
                ::typespace::build::Type::Map("String".to_string(), "Item".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "Bag".to_string(),
                ::typespace::build::Struct::<String>::new()
                    .name("Bag")
                    .properties([
                        ::typespace::build::StructProperty::new(
                                "items",
                                "Vec<Nullable<Item>>".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                        ::typespace::build::StructProperty::new(
                                "by_name",
                                "Map<String, Item>".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                    ])
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
    };
}
