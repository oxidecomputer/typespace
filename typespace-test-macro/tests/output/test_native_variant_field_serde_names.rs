fn expansion() {
    {
        let mut builder = ::typespace::TypespaceBuilder::<
            String,
        >::new(Settings::typical());
        builder
            .insert(
                "u32".to_string(),
                ::typespace::build::Type::Integer("u32".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "Inner".to_string(),
                ::typespace::build::Struct::<String>::new()
                    .name("Inner")
                    .properties([
                        ::typespace::build::StructProperty::new(
                                "value",
                                "u32".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                    ])
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
            .insert(
                "Shape".to_string(),
                ::typespace::build::Enum::<String>::new()
                    .name("Shape")
                    .tag_type(::typespace::build::EnumTagType::External)
                    .variants([
                        ::typespace::build::EnumVariant::new(
                            "Rect",
                            ::typespace::build::VariantDetails::<
                                String,
                            >::Struct(
                                [
                                    ::typespace::build::StructProperty::new(
                                            "top_left",
                                            "u32".to_string(),
                                        )
                                        .with_state(
                                            ::typespace::build::StructPropertyState::Default,
                                        )
                                        .with_json_name(
                                            ::typespace::build::StructPropertySerde::Rename(
                                                "top-left".to_string(),
                                            ),
                                        ),
                                    ::typespace::build::StructProperty::new(
                                            "inner",
                                            "Inner".to_string(),
                                        )
                                        .with_state(
                                            ::typespace::build::StructPropertyState::Required,
                                        )
                                        .with_json_name(
                                            ::typespace::build::StructPropertySerde::Flatten,
                                        ),
                                ]
                                    .into_iter()
                                    .collect(),
                            ),
                        ),
                    ])
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
    };
}
