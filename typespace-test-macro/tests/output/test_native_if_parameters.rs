fn expansion() {
    {
        let mut builder = ::typespace::TypespaceBuilder::<
            String,
        >::new(Settings::typical());
        builder
            .insert(
                "u32".to_string(),
                ::typespace::build::Type::Integer("u32".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "Inner".to_string(),
                ::typespace::build::Struct::<String>::new()
                    .name("Inner")
                    .properties([
                        ::typespace::build::StructProperty::new(
                                "count",
                                "u32".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                    ])
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
            .insert(
                "::foo::Wrapper<Inner>".to_string(),
                ::typespace::build::Type::Native(
                    ::typespace::build::Native::new(
                            "::foo::Wrapper",
                            [::typespace::TypespaceTrait::Debug]
                                .into_iter()
                                .collect::<::typespace::TypespaceTraitSet>(),
                            ["Inner".to_string()].into_iter().collect(),
                        )
                        .with_disposition(
                            ::typespace::TypespaceTrait::Clone,
                            ::typespace::TraitProvision::IfParameters,
                        )
                        .with_disposition(
                            ::typespace::TypespaceTrait::PartialEq,
                            ::typespace::TraitProvision::IfParameters,
                        ),
                ),
            )
            .unwrap();
        builder
            .insert(
                "Wrapped".to_string(),
                ::typespace::build::TypeAlias::<
                    String,
                >::new("::foo::Wrapper<Inner>".to_string())
                    .name("Wrapped")
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
    };
}
