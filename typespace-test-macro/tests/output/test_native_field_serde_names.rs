fn expansion() {
    {
        let mut builder = ::typespace::TypespaceBuilder::<
            String,
        >::new(Settings::typical());
        builder
            .insert(
                "u32".to_string(),
                ::typespace::build::Type::Integer("u32".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "Inner".to_string(),
                ::typespace::build::Struct::<String>::new()
                    .name("Inner")
                    .properties([
                        ::typespace::build::StructProperty::new(
                                "value",
                                "u32".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                    ])
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder.insert("String".to_string(), ::typespace::build::Type::String).unwrap();
        builder
            .insert(
                "Outer".to_string(),
                ::typespace::build::Struct::<String>::new()
                    .name("Outer")
                    .properties([
                        ::typespace::build::StructProperty::new(
                                "my_field",
                                "String".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            )
                            .with_json_name(
                                ::typespace::build::StructPropertySerde::Rename(
                                    "my-field".to_string(),
                                ),
                            ),
                        ::typespace::build::StructProperty::new(
                                "inner",
                                "Inner".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            )
                            .with_json_name(
                                ::typespace::build::StructPropertySerde::Flatten,
                            ),
                        ::typespace::build::StructProperty::new(
                                "count",
                                "u32".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::DefaultValue(
                                    ::typespace::build::JsonValue::new(
                                        ::serde_json::Value::Number(
                                            ::serde_json::Number::from(7i64),
                                        ),
                                    ),
                                ),
                            )
                            .with_json_name(
                                ::typespace::build::StructPropertySerde::Rename(
                                    "count-x".to_string(),
                                ),
                            ),
                    ])
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
    };
}
