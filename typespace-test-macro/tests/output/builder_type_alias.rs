fn expansion() {
    {
        let mut builder = ::typespace::TypespaceBuilder::<
            String,
        >::new(Settings::typical());
        builder
            .insert(
                "u32".to_string(),
                ::typespace::build::Type::Integer("u32".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "Item".to_string(),
                ::typespace::build::Struct::<String>::new()
                    .name("Item")
                    .properties([
                        ::typespace::build::StructProperty::new(
                                "value",
                                "u32".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                    ])
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
            .insert(
                "Vec<Item>".to_string(),
                ::typespace::build::Type::Vec("Item".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "ItemList".to_string(),
                ::typespace::build::TypeAlias::<String>::new("Vec<Item>".to_string())
                    .name("ItemList")
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
    };
}
