fn expansion() {
    {
        let mut builder = ::typespace::TypespaceBuilder::<
            String,
        >::new(Settings::typical());
        builder
            .insert(
                "::uuid::Uuid".to_string(),
                ::typespace::build::Type::Native(
                    ::typespace::build::Native::new(
                        "::uuid::Uuid",
                        [
                            ::typespace::TypespaceTrait::Clone,
                            ::typespace::TypespaceTrait::Debug,
                            ::typespace::TypespaceTrait::Eq,
                            ::typespace::TypespaceTrait::PartialEq,
                            ::typespace::TypespaceTrait::Ord,
                            ::typespace::TypespaceTrait::PartialOrd,
                            ::typespace::TypespaceTrait::Hash,
                        ]
                            .into_iter()
                            .collect::<::typespace::TypespaceTraitSet>(),
                        [].into_iter().collect(),
                    ),
                ),
            )
            .unwrap();
        builder
            .insert(
                "Vec<::uuid::Uuid>".to_string(),
                ::typespace::build::Type::Vec("::uuid::Uuid".to_string()),
            )
            .unwrap();
        builder.insert("String".to_string(), ::typespace::build::Type::String).unwrap();
        builder
            .insert(
                "Map<::uuid::Uuid, String>".to_string(),
                ::typespace::build::Type::Map(
                    "::uuid::Uuid".to_string(),
                    "String".to_string(),
                ),
            )
            .unwrap();
        builder
            .insert(
                "Batch".to_string(),
                ::typespace::build::Struct::<String>::new()
                    .name("Batch")
                    .properties([
                        ::typespace::build::StructProperty::new(
                                "ids",
                                "Vec<::uuid::Uuid>".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                        ::typespace::build::StructProperty::new(
                                "primary",
                                "::uuid::Uuid".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Optional,
                            ),
                        ::typespace::build::StructProperty::new(
                                "by_id",
                                "Map<::uuid::Uuid, String>".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                    ])
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
    };
}
