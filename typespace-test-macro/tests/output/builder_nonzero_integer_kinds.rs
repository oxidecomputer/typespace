fn expansion() {
    {
        let mut builder = ::typespace::TypespaceBuilder::<
            String,
        >::new(Settings::typical());
        builder
            .insert(
                "NonZeroU8".to_string(),
                ::typespace::build::Type::Integer("::std::num::NonZeroU8".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "NonZeroU64".to_string(),
                ::typespace::build::Type::Integer("::std::num::NonZeroU64".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "NonZeroUsize".to_string(),
                ::typespace::build::Type::Integer("::std::num::NonZeroUsize".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "NonZeroI32".to_string(),
                ::typespace::build::Type::Integer("::std::num::NonZeroI32".to_string()),
            )
            .unwrap();
        builder
            .insert(
                "Test".to_string(),
                ::typespace::build::Struct::<String>::new()
                    .name("Test")
                    .properties([
                        ::typespace::build::StructProperty::new(
                                "a",
                                "NonZeroU8".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                        ::typespace::build::StructProperty::new(
                                "b",
                                "NonZeroU64".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                        ::typespace::build::StructProperty::new(
                                "c",
                                "NonZeroUsize".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                        ::typespace::build::StructProperty::new(
                                "d",
                                "NonZeroI32".to_string(),
                            )
                            .with_state(
                                ::typespace::build::StructPropertyState::Required,
                            ),
                    ])
                    .build()
                    .unwrap(),
            )
            .unwrap();
        builder
    };
}
